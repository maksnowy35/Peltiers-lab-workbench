"""Export of candidate designs back to ANSYS Workbench (closing the loop).

Two artifacts are produced:
* a design-point table (CSV) with geometry and current columns, and
* a Workbench journal (IronPython) that creates the same design points in the
  project's Parameter Set.  The journal uses the standard Workbench scripting
  calls (Parameters.GetParameter / CreateDesignPoint / SetParameterExpression);
  parameter IDs (P1, P2, ...) must be mapped to the user's project, and it is
  a template to be checked on the local Workbench version.
"""

from __future__ import annotations

import csv
import io
from datetime import datetime

__all__ = ["DEFAULT_PARAM_MAP", "design_point_rows", "design_points_csv", "workbench_journal"]

DEFAULT_PARAM_MAP = {
    "a_hot_mm": "P1",
    "a_cold_mm": "P2",
    "height_mm": "P3",
    "current_a": "P4",
}

UNITS = {
    "a_hot_mm": "mm",
    "a_cold_mm": "mm",
    "height_mm": "mm",
    "theta_deg": "deg",
    "current_a": "A",
    "tcc": "W m^-2 C^-1",
    "ecc": "S m^-2",
}


def design_point_rows(designs: list[dict], currents: list[float]) -> list[dict]:
    """Cartesian product of geometries and currents -> list of design points."""
    rows = []
    for d in designs:
        for i in currents:
            rows.append(
                {
                    "name": d.get("name", ""),
                    "a_hot_mm": round(float(d["a_hot_mm"]), 5),
                    "a_cold_mm": round(float(d["a_cold_mm"]), 5),
                    "height_mm": round(float(d["height_mm"]), 5),
                    "theta_deg": round(float(d.get("theta_deg", 0.0)), 4),
                    "current_a": round(float(i), 6),
                }
            )
    return rows


def design_points_csv(rows: list[dict], param_map: dict[str, str] | None = None) -> str:
    """Workbench-style table: comment header with parameter definitions, Name/Pn header, Units row."""
    pm = param_map or DEFAULT_PARAM_MAP
    keys = [k for k in pm if rows and k in rows[0]]
    buf = io.StringIO()
    buf.write("#\n# Design points generated by teglab " + datetime.now().strftime("%Y-%m-%d %H:%M") + "\n")
    buf.write("# The parameters defined in the project are:\n")
    buf.write("# " + ", ".join(f"{pm[k]} - {k}" for k in keys) + "\n#\n")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["Name", *[pm[k] for k in keys], "Note"])
    w.writerow(["Units", *[UNITS.get(k, "") for k in keys], ""])
    for n, r in enumerate(rows):
        w.writerow([f"DP {n}", *[r[k] for k in keys], r.get("name", "")])
    return buf.getvalue()


def workbench_journal(
    rows: list[dict],
    param_map: dict[str, str] | None = None,
    update: bool = False,
    export_path: str = r"C:\temp\teglab_design_points.csv",
) -> str:
    pm = param_map or DEFAULT_PARAM_MAP
    keys = [k for k in pm if rows and k in rows[0]]
    lines = [
        "# encoding: utf-8",
        "# Workbench journal generated by teglab - creates design points for the selected designs.",
        "# Run: Workbench > File > Scripting > Run Script File...  (save the project first!)",
        "# Check that the parameter IDs below match your Parameter Set before running.",
        "",
        "PARAM = {",
        *[f'    "{k}": "{pm[k]}",  # [{UNITS.get(k, "")}]' for k in keys],
        "}",
        "UNITS = {",
        *[f'    "{k}": "{UNITS.get(k, "")}",' for k in keys],
        "}",
        "ROWS = [",
    ]
    for r in rows:
        items = ", ".join(f'"{k}": {r[k]!r}' for k in keys)
        lines.append(f"    {{{items}}},  # {r.get('name', '')}")
    lines += [
        "]",
        "",
        "def expression(key, value):",
        "    unit = UNITS.get(key)",
        '    return "%s [%s]" % (repr(value), unit) if unit else repr(value)',
        "",
        "params = dict((key, Parameters.GetParameter(Name=pid)) for key, pid in PARAM.items())",
        'first = Parameters.GetDesignPoint(Name="0")',
        "for index, row in enumerate(ROWS):",
        "    dp = first if index == 0 else Parameters.CreateDesignPoint(Retained=False)",
        "    for key, value in row.items():",
        "        dp.SetParameterExpression(Parameter=params[key], Expression=expression(key, value))",
        "",
    ]
    if update:
        lines += [
            "UpdateAllDesignPoints()",
            f'Parameters.ExportAllDesignPointsData(FilePath=r"{export_path}")',
        ]
    else:
        lines += [
            "# Solve all design points and export the table for teglab (uncomment):",
            "# UpdateAllDesignPoints()",
            f'# Parameters.ExportAllDesignPointsData(FilePath=r"{export_path}")',
        ]
    return "\n".join(lines) + "\n"
