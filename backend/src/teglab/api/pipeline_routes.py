"""REST endpoints of the ingestion pipeline (``/api/pipeline``).

Multipart uploads in, typed Pydantic models out - the OpenAPI schema at ``/docs`` documents both, and
``frontend/src/app/core/pipeline.models.ts`` mirrors every model (generated by
``backend/scripts/gen_ts_types.py``).  Handlers are plain ``def`` because parsing and fitting are
CPU-bound (FastAPI runs them in a thread pool).

Nodal datasets live in an in-process store (``app.state.nodal_store``): run a single server process
(the Docker image does), or pin clients to one worker.
"""

from __future__ import annotations

import json
import re
from typing import Annotated, Literal

from fastapi import APIRouter, File, Form, HTTPException, Path, Query, Request, Response, UploadFile, status
from pydantic import ValidationError

from ..pipeline import PipelineReport, RunOptions, inspect_files, load_profile, run_pipeline
from ..pipeline.nodal import DatasetStore, NodalDataset, build_dataset, demo_archive, demo_dataset
from ..pipeline.nodal import evaluate_profile as nodal_profile
from ..pipeline.nodal import project_points as nodal_points
from ..pipeline.overlay import placement
from ..pipeline.schemas import (
    PROFILE_DIR,
    DeleteResult,
    ExampleInfo,
    ImageCalibration,
    LayerProfile,
    NodalDatasetInfo,
    NodalPoints,
    OverlayPlacement,
    PointsRequest,
    ProfileRequest,
    ProjectProfile,
    RunSettings,
)

router = APIRouter(prefix="/api/pipeline", tags=["pipeline"])

PROFILE_NAME = re.compile(r"[A-Za-z0-9_-]{1,64}")
MAX_UPLOAD_BYTES = 50 * 1024 * 1024  # a nodal export of the C2 mesh is ~5 MB per quantity
MAX_UPLOAD_FILES = 500
EXAMPLES_DIR = PROFILE_DIR.with_name("examples")
MEDIA_TYPES = {".csv": "text/csv", ".txt": "text/plain", ".zip": "application/zip"}

DatasetId = Annotated[str, Path(pattern=r"^[0-9a-f]{32}$", description="From POST /nodal")]
ImageName = Annotated[str, Path(pattern=r"^[A-Za-z0-9_.-]{1,128}$")]


def _profile(name: str) -> ProjectProfile:
    if not PROFILE_NAME.fullmatch(name):  # bundled profiles only - never a path on the server
        raise HTTPException(400, "profile must be the name of a bundled profile")
    try:
        return load_profile(name)
    except FileNotFoundError as exc:
        raise HTTPException(404, f"unknown profile '{name}'") from exc


def _read(files: list[UploadFile]) -> list[tuple[str, bytes]]:
    if len(files) > MAX_UPLOAD_FILES:
        raise HTTPException(413, f"more than {MAX_UPLOAD_FILES} files: upload a zip archive instead")
    out = []
    for f in files:
        data = f.file.read(MAX_UPLOAD_BYTES + 1)
        if len(data) > MAX_UPLOAD_BYTES:
            raise HTTPException(413, f"{f.filename}: larger than {MAX_UPLOAD_BYTES // 2**20} MB")
        out.append((f.filename or "upload", data))
    return out


def _store(request: Request) -> DatasetStore:
    return request.app.state.nodal_store


def _dataset(request: Request, dataset_id: str) -> NodalDataset:
    try:
        return _store(request).get(dataset_id)
    except KeyError as exc:
        raise HTTPException(404, "dataset not found (expired or deleted): upload the files again") from exc


def _unprocessable(exc: ValidationError) -> HTTPException:
    return HTTPException(422, json.loads(exc.json(include_url=False)))


# ----------------------------------------------------------------------------------- parameter runs
@router.get("/profiles")
def profiles() -> list[str]:
    return sorted(p.stem for p in PROFILE_DIR.glob("*.json"))


@router.get("/profiles/{name}")
def profile(name: str) -> ProjectProfile:
    return _profile(name)


@router.post("/inspect")
def inspect(files: list[UploadFile] = File(...), profile: str = Form("thesis-2026")) -> PipelineReport:
    """Detect the format of every file and show how each parameter would be interpreted."""
    return inspect_files(_read(files), _profile(profile))


@router.post("/run")
def run(
    files: list[UploadFile] = File(...),
    settings: str = Form("{}", description='RunSettings as JSON, e.g. {"variants": {"B": "A5"}}'),
) -> PipelineReport:
    """Run the full pipeline: canonical frame, per-system physics, variant comparison and issues."""
    try:
        s = RunSettings.model_validate_json(settings)
    except ValidationError as exc:
        raise _unprocessable(exc) from exc
    options = RunOptions(
        profile=_profile(s.profile),
        default_condition=s.default_condition,
        conditions=s.conditions,
        variants=s.variants,
        meshes=s.meshes,
        reference_variant=s.reference_variant,
        calibration=s.calibration,
    )
    return run_pipeline(_read(files), options).report


# ------------------------------------------------------------------------------------------ examples
def _examples() -> list[ExampleInfo]:
    out = []
    for entry in json.loads((EXAMPLES_DIR / "index.json").read_text(encoding="utf-8")):
        name = entry["name"]
        if name.startswith("synthetic-cell_"):
            size = len(demo_archive(name.endswith("contacts-applied.zip")))
        else:
            size = (EXAMPLES_DIR / name).stat().st_size
        out.append(ExampleInfo(**entry, size_bytes=size))
    return out


@router.get("/examples")
def examples() -> list[ExampleInfo]:
    """Parameter tables reconstructed from the thesis and synthetic nodal exports to try the pipeline."""
    return _examples()


@router.get("/examples/{name}", response_class=Response, responses={200: {"content": {"application/octet-stream": {}}}})
def example(name: Annotated[str, Path(pattern=r"^[A-Za-z0-9_.-]{1,128}$")]) -> Response:
    known = {e.name: e for e in _examples()}
    if name not in known:
        raise HTTPException(404, "example not found")
    if name.startswith("synthetic-cell_"):
        data = demo_archive(name.endswith("contacts-applied.zip"))
    else:
        data = (EXAMPLES_DIR / name).read_bytes()
    suffix = name[name.rfind(".") :]
    headers = {"Content-Disposition": f'attachment; filename="{name}"'}
    return Response(data, media_type=MEDIA_TYPES.get(suffix, "application/octet-stream"), headers=headers)


# --------------------------------------------------------------------------------------- nodal data
@router.post("/nodal", status_code=status.HTTP_201_CREATED)
def nodal_upload(request: Request, files: list[UploadFile] = File(...)) -> NodalDatasetInfo:
    """Upload Mechanical nodal exports: text files, a zip of an export folder, manifest.json, PNG contours."""
    ds = build_dataset(_read(files))
    _store(request).put(ds)
    return ds.info()


@router.post("/nodal/demo", status_code=status.HTTP_201_CREATED)
def nodal_demo(request: Request, contacts: Literal["applied", "bonded"] = Query("applied")) -> NodalDatasetInfo:
    """The synthetic unit cell as a dataset - the same ingestion path as an upload."""
    ds = demo_dataset(contacts == "applied")
    _store(request).put(ds)
    return ds.info()


@router.get("/nodal/{dataset_id}")
def nodal_info(request: Request, dataset_id: DatasetId) -> NodalDatasetInfo:
    return _dataset(request, dataset_id).info()


@router.delete("/nodal/{dataset_id}")
def nodal_delete(request: Request, dataset_id: DatasetId) -> DeleteResult:
    return DeleteResult(deleted=_store(request).delete(dataset_id))


@router.get(
    "/nodal/{dataset_id}/images/{name}", response_class=Response, responses={200: {"content": {"image/png": {}}}}
)
def nodal_image(request: Request, dataset_id: DatasetId, name: ImageName) -> Response:
    ds = _dataset(request, dataset_id)
    if name not in ds.images:
        raise HTTPException(404, "image not found")
    return Response(ds.images[name].data, media_type="image/png", headers={"Cache-Control": "private, max-age=3600"})


@router.post("/nodal/{dataset_id}/profile")
def nodal_layer_profile(request: Request, dataset_id: DatasetId, req: ProfileRequest) -> LayerProfile:
    """Layer temperatures hot → cold, the ΔT split and effective contact conductances (TCC_eff, ECC_eff)."""
    ds = _dataset(request, dataset_id)
    expected = req.contacts or _profile(req.profile).contacts
    return nodal_profile(ds, req, expected)


@router.post("/nodal/{dataset_id}/points")
def nodal_view_points(request: Request, dataset_id: DatasetId, req: PointsRequest) -> NodalPoints:
    """Nodal values projected onto a standard view (the data layer of the overlay viewer)."""
    return nodal_points(_dataset(request, dataset_id), req)


# ------------------------------------------------------------------------------------------- overlay
@router.post("/overlay")
def overlay(cal: ImageCalibration) -> OverlayPlacement:
    """Where a calibrated picture lands on the model axes (Plotly ``layout.images`` placement)."""
    return placement(cal)
